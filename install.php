<?php
// MyPress installer. Installation is one-time and creates a random application secret.
declare(strict_types=1);
error_reporting(E_ALL);
$root = __DIR__;
$configFile = $root . '/config.php';
$lockFile = $root . '/data/installed.lock';
if (file_exists($configFile) && file_exists($lockFile)) {
    http_response_code(403);
    exit('MyPress قبلاً نصب شده است. برای نصب مجدد، ابتدا از اطلاعات نسخه فعلی پشتیبان تهیه کنید.');
}
require_once $root . '/includes/db.php';
require_once $root . '/includes/helpers.php';
mp_session_start();
$error = '';
$done = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    mp_csrf_check();
    $siteTitle = trim((string)($_POST['site_title'] ?? 'سایت من'));
    $adminUser = trim((string)($_POST['admin_user'] ?? ''));
    $adminPass = (string)($_POST['admin_pass'] ?? '');
    $adminEmail = trim((string)($_POST['admin_email'] ?? ''));
    $dbType = ($_POST['db_type'] ?? 'sqlite') === 'mysql' ? 'mysql' : 'sqlite';

    if ($siteTitle === '' || strlen($siteTitle) > 150 ||
        !preg_match('/^[a-zA-Z0-9_.-]{3,60}$/', $adminUser) ||
        strlen($adminPass) < 12 || strlen($adminPass) > 4096 ||
        !filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) {
        $error = 'عنوان سایت، نام کاربری (۳ تا ۶۰ نویسه انگلیسی)، ایمیل یا رمز عبور معتبر نیست. رمز باید حداقل ۱۲ نویسه باشد.';
    } else {
        $dataDirectory = $root . '/data';
        if (!is_dir($dataDirectory) && !mkdir($dataDirectory, 0750, true) && !is_dir($dataDirectory)) {
            $error = 'ساخت پوشه داده امکان‌پذیر نیست.';
        } else {
            $config = [
                'db_type' => $dbType,
                'db_path' => $dataDirectory . '/mypress.sqlite',
                'db_host' => trim((string)($_POST['db_host'] ?? 'localhost')),
                'db_name' => trim((string)($_POST['db_name'] ?? 'mypress')),
                'db_user' => trim((string)($_POST['db_user'] ?? 'root')),
                'db_pass' => (string)($_POST['db_pass'] ?? ''),
                'db_charset' => 'utf8mb4',
                'secret_key' => bin2hex(random_bytes(32)),
                'lang' => 'fa',
                'debug' => false,
            ];
            $temporaryConfig = $configFile . '.installing';
            $configWritten = false;
            try {
                $source = "<?php\n// Generated by MyPress installer. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
                if (file_put_contents($temporaryConfig, $source, LOCK_EX) === false ||
                    !rename($temporaryConfig, $configFile)) {
                    throw new RuntimeException('Unable to write configuration.');
                }
                $configWritten = true;
                $pdo = mp_pdo();
                $pdo->beginTransaction();
                mp_create_tables($pdo);
                $insert = $pdo->prepare("INSERT INTO users (username,password_hash,email,display_name,role) VALUES (?,?,?,?, 'admin')");
                $insert->execute([$adminUser, password_hash($adminPass, PASSWORD_DEFAULT), $adminEmail, $adminUser]);
                $adminId = (int)$pdo->lastInsertId();
                mp_seed($pdo, $adminId);
                $pdo->commit();

                mp_set_option('site_title', $siteTitle);
                mp_set_option('site_description', 'سایت شخصی من با MyPress');
                mp_set_option('site_lang', 'fa');
                mp_set_option('module_shop', '1');
                mp_set_option('module_comments', '1');
                mp_set_option('module_seo', '1');

                if (file_put_contents($lockFile, date('c'), LOCK_EX) === false) {
                    throw new RuntimeException('Unable to create installation lock.');
                }
                $done = true;
            } catch (Throwable $exception) {
                if (isset($pdo) && $pdo instanceof PDO && $pdo->inTransaction()) $pdo->rollBack();
                if ($configWritten) @unlink($configFile);
                @unlink($temporaryConfig);
                $error = 'نصب کامل نشد. تنظیمات دیتابیس و مجوز نوشتن پوشه data را بررسی کنید؛ جزئیات فنی در پاسخ عمومی نمایش داده نمی‌شود.';
                error_log('MyPress installation error: ' . $exception->getMessage());
            }
        }
    }
}
?>
<!DOCTYPE html><html lang="fa" dir="rtl"><head><meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>نصب MyPress</title><link rel="stylesheet" href="assets/css/admin.css"></head>
<body><main class="install-box">
<h1>🧩 نصب MyPress</h1>
<p>سیستم مدیریت وب‌سایت شخصی — سبک و مستقل.</p>
<?php if ($done): ?>
<div class="flash flash-ok">نصب کامل شد.</div>
<p><a class="btn" href="index.php">مشاهده سایت</a> <a class="btn" href="admin/login.php">ورود به پنل مدیریت</a></p>
<p><small>نام کاربری مدیر: <b><?= e($adminUser) ?></b> — رمز را امن نگه دارید.</small></p>
<?php else: ?>
<?php if ($error): ?><div class="flash flash-err"><?= e($error) ?></div><?php endif; ?>
<form method="post"><?= mp_csrf_field() ?>
<label>عنوان سایت <input name="site_title" required maxlength="150" value="سایت من"></label>
<label>نام کاربری مدیر <input name="admin_user" required minlength="3" maxlength="60" pattern="[A-Za-z0-9_.-]+" dir="ltr" autocomplete="username"></label>
<label>رمز عبور مدیر (حداقل ۱۲ نویسه) <input type="password" name="admin_pass" required minlength="12" maxlength="4096" dir="ltr" autocomplete="new-password"></label>
<label>ایمیل مدیر <input type="email" name="admin_email" required dir="ltr"></label>
<label>پایگاه داده <select name="db_type" id="db_type"><option value="sqlite">SQLite</option><option value="mysql">MySQL / MariaDB</option></select></label>
<div id="mysql-fields" style="display:none">
<label>هاست <input name="db_host" value="localhost" dir="ltr"></label>
<label>نام دیتابیس <input name="db_name" value="mypress" dir="ltr"></label>
<label>کاربر دیتابیس <input name="db_user" value="root" dir="ltr"></label>
<label>رمز دیتابیس <input type="password" name="db_pass" dir="ltr"></label>
</div>
<button class="btn" type="submit">نصب MyPress</button>
</form>
<script>document.getElementById('db_type').addEventListener('change',function(){document.getElementById('mysql-fields').style.display=this.value==='mysql'?'block':'none';});</script>
<?php endif; ?>
</main></body></html>
